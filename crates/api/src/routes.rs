//! The route table: every route the API serves, who may call it, the rules it enforces and its
//! request and response types. The router is built from this table, and `crates/contracts`
//! writes the OpenAPI paths from it, so a route cannot be served without being in the contract
//! (ADR-011). Schema names are the boundary types' names in `contracts/schemas/`.
