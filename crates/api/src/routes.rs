#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Method {
    Get,
    Post,
    Put,
    Patch,
}

impl Method {
    pub fn as_str(self) -> &'static str {
        match self {
            Method::Get => "get",
            Method::Post => "post",
            Method::Put => "put",
            Method::Patch => "patch",
        }
    }
}

/// Who may call a route (`auth::Principal`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Access {
    Public,
    Customer,
    Partner,
    Staff,
    Feed,
}

/// A request or response body.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Body {
    Empty,
    /// Plain text: a liveness answer, or a source's own payload.
    Text,
    Json(&'static str),
    JsonList(&'static str),
    /// Server-sent events, each carrying this type as JSON.
    Events(&'static str),
}

pub struct Route {
    pub method: Method,
    pub path: &'static str,
    pub access: Access,
    pub summary: &'static str,
    /// The rules in `docs/rules.md` the route enforces.
    pub rules: &'static [&'static str],
    /// Optional query parameters, all strings.
    pub query: &'static [&'static str],
    pub request: Body,
    pub response: Body,
    pub handler: fn() -> MethodRouter<AppState>,
}

